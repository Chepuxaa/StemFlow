let language = 'en';
const localizedNodes = [];
const localizedAttributes = [];
const staticKeys = new Map();
for (const catalog of Object.values(translations)) for (const [key, value] of Object.entries(catalog)) if (!key.startsWith('stage_') && !value.includes('{')) staticKeys.set(value, key);
staticKeys.set('Generator', 'navGenerator');
staticKeys.set('Settings', 'navSettings');
staticKeys.set('Добавь треки. Остальное возьмёт на себя GPU.', 'playlistHelp');
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (['SCRIPT','STYLE'].includes(node.parentElement.tagName)) continue;
  const key = staticKeys.get(node.textContent.trim());
  if (key) localizedNodes.push({node, key, prefix:node.textContent.match(/^\s*/)[0], suffix:node.textContent.match(/\s*$/)[0]});
}
for (const node of document.querySelectorAll('[title],[aria-label]')) for (const attribute of ['title','aria-label']) {
  const key = staticKeys.get(node.getAttribute(attribute));
  if (key) localizedAttributes.push({node,key,attribute});
}
function t(key, values={}) {
  return (translations[language][key] || key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}
function applyLanguage(value) {
  language = value === 'ru' ? 'ru' : 'en';
  document.documentElement.lang = language;
  document.getElementById('language').value = language;
  for (const entry of localizedNodes) entry.node.textContent = entry.prefix + t(entry.key) + entry.suffix;
  for (const entry of localizedAttributes) entry.node.setAttribute(entry.attribute,t(entry.key));
}
applyLanguage('en');
